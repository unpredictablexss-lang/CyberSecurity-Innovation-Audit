#!/usr/bin/env python3
"""Inventory node_modules source inputs referenced by the exact rk3568 Ninja graph."""
from __future__ import annotations

import hashlib
import json
import posixpath
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = Path("/home/deepsleep/c-line-c1-profile-20261018")
SOURCE = BASE / "openharmony-git-archive-20261019"
MATERIALIZATION = HERE / "materialization_manifest_20261019.json"
INPUT_INVENTORY = HERE / "ninja_input_inventory_20261019.v1.json"
RESULT = HERE / "ninja_node_modules_inputs_20261019.v1.json"


def sha(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def source_relative(build_prefix: str) -> str | None:
    prefix = build_prefix.strip("\"'=:;")
    normalized = posixpath.normpath(prefix)
    if normalized.startswith("../../"):
        return normalized[6:]
    if normalized.startswith("/src/"):
        return normalized[5:]
    if normalized.startswith("../"):
        return normalized[3:]
    return None


def main() -> int:
    project_manifest = json.loads(MATERIALIZATION.read_text(encoding="utf-8"))
    projects = {item["path"]: item for item in project_manifest["projects"]}
    inventory = json.loads(INPUT_INVENTORY.read_text(encoding="utf-8"))
    ref_counts: Counter[str] = Counter()
    samples: dict[str, str] = {}
    for item in inventory["node_modules_reference_roots"]:
        prefix = item["build_path_root"]
        root = source_relative(prefix)
        if root is None:
            root = "UNRESOLVED:" + prefix
        ref_counts[root] += item["reference_count"]
        samples.setdefault(root, item["example"])
    rows = []
    for root, count in sorted(ref_counts.items()):
        row: dict[str, object] = {"source_root": root, "graph_reference_count": count, "sample": samples[root]}
        if root.startswith("UNRESOLVED:"):
            row["status"] = "unresolved_build_path"
        else:
            source = SOURCE / root
            row["source_exists"] = source.is_dir()
            row["package_json_exists"] = (source / "package.json").is_file()
            row["package_lock_exists"] = (source / "package-lock.json").is_file()
            row["shrinkwrap_exists"] = (source / "npm-shrinkwrap.json").is_file()
            if (source / "package.json").is_file():
                row["package_json_sha256"] = sha(source / "package.json")
            if (source / "package-lock.json").is_file():
                row["package_lock_sha256"] = sha(source / "package-lock.json")
            candidates = [path for path in projects if root == path or root.startswith(path + "/")]
            if candidates:
                pin = projects[max(candidates, key=len)]
                row["manifest_project"] = pin["path"]
                row["manifest_commit"] = pin["commit"]
                row["manifest_tree"] = pin["tree"]
            else:
                row["manifest_project"] = None
        rows.append(row)
    result = {
        "schema": "ohscanner.c1.ninja-node-modules-inputs/v1",
        "status": "inventory_captured_from_ninja_tool_inputs",
        "product": "hihope/rk3568",
        "build_ninja_sha256": inventory["build_ninja_sha256"],
        "input_inventory_sha256": sha(INPUT_INVENTORY),
        "materialization_manifest_sha256": sha(MATERIALIZATION),
        "reference_count": sum(ref_counts.values()),
        "dependency_root_count": len(rows),
        "roots": rows,
        "scope_note": "Roots are derived from the successful read-only `ninja -t inputs all` inventory, not raw build.ninja text. They identify graph inputs only and do not prove that every root is missing or required for a successful image build.",
    }
    RESULT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": result["status"], "reference_count": result["reference_count"],
                      "dependency_root_count": result["dependency_root_count"], "roots": rows}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
